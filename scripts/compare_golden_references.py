"""Compare two golden-probability references and attribute every difference to an approved cause.

Usage:
    python scripts/compare_golden_references.py BEFORE.json AFTER.json OUT.md

Approved M2 causes:
  E1  synthetic XGBoost blend weight -> 0   (estimate_probabilities: fixtures whose source was "hybrid")
  E2  unknown club teams report 0 matches   (any output of a fixture containing a hash-fallback team)
  E3  synthetic XGBoost removed from BILQE consensus (match_analysis "qualification" block, any fixture)
Any difference not covered by these is reported as UNINTENDED; the script exits 1 if one exists.
"""
from __future__ import annotations

import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
_tmp = tempfile.mkdtemp()
os.environ.update(HOME=_tmp, FOOTBALL_PREDICTOR_DB_PATH=os.path.join(_tmp, "engine.db"))

from tests.golden.test_golden_probabilities import FIXTURES, SEEDED_TEAM_STATE, _diff  # noqa: E402


def _seed_isolated_db():
    import sqlite3

    import src.db.database as database
    from src.db.team_state import TeamState, upsert_team_state
    from tests.golden.test_golden_probabilities import LEGACY_TABLES_SQL

    conn = sqlite3.connect(":memory:", check_same_thread=False)
    conn.row_factory = sqlite3.Row
    database.init_db(conn)
    conn.executescript(LEGACY_TABLES_SQL.read_text())
    for team, league, played, scored, conceded, form in SEEDED_TEAM_STATE:
        upsert_team_state(conn, TeamState(
            team_name=team, league=league, venue="overall", elo=1500.0 + 10 * played,
            rolling_scored=scored, rolling_conceded=conceded, form_last5=form, matches_played=played,
        ))
    database._connection = conn


def _resolves_to_hash_fallback(team: str, venue: str, league_key: str) -> bool:
    """True when get_team_stats() takes the unknown-club hash path (the only path K2 changed)."""
    from src.ml.team_stats_db import _INTERNATIONAL_LEAGUES, get_team_stats

    lower = league_key.lower()
    international = league_key in _INTERNATIONAL_LEAGUES or league_key == "International" or any(
        k in lower for k in ("world cup", "international", "nations league", "euro", "copa", "qualification")
    )
    return not international and get_team_stats(team, venue, league_key).matches_played == 0


def _blind_fixtures() -> dict[str, set[str]]:
    """Fixtures with a hash-fallback team, per section (each path maps league names its own way)."""
    from api.services.match_analysis_service import LEAGUE_NAME_MAP
    from src.engine.probability_engine import LEAGUE_KEY_MAP

    _seed_isolated_db()
    key_for = {
        "estimate_probabilities": lambda lg: LEAGUE_KEY_MAP.get(lg, "default"),
        "match_analysis": lambda lg: LEAGUE_NAME_MAP.get(lg, lg),
    }
    return {
        section: {
            f"{h} v {a} [{lg}]" for h, a, lg, _ in FIXTURES
            if _resolves_to_hash_fallback(h, "home", key(lg)) or _resolves_to_hash_fallback(a, "away", key(lg))
        }
        for section, key in key_for.items()
    }


def _attribute(section: str, fixture: str, path: str, before: dict, blind: dict[str, set[str]]) -> str | None:
    if fixture in blind[section]:
        return "E2"
    if section == "estimate_probabilities" and before["estimate_probabilities"][fixture]["source"] == "hybrid":
        return "E1"
    if section == "match_analysis" and path.startswith(f"$.match_analysis.{fixture}.qualification"):
        return "E3"
    return None


def _fmt(v):
    return f"{v:.4f}".rstrip("0").rstrip(".") if isinstance(v, float) else str(v)


def main(before_path: str, after_path: str, out_path: str) -> int:
    before = json.loads(Path(before_path).read_text())
    after = json.loads(Path(after_path).read_text())
    blind = _blind_fixtures()

    attributed: dict[str, list[str]] = {"E1": [], "E2": [], "E3": []}
    unintended: list[str] = []
    for section in ("estimate_probabilities", "match_analysis"):
        for fixture in sorted(set(before[section]) | set(after[section])):
            for line in _diff(before[section].get(fixture), after[section].get(fixture), f"$.{section}.{fixture}"):
                cause = _attribute(section, fixture, line, before, blind)
                (attributed[cause] if cause else unintended).append(line)

    lines = [
        "# M2 — Before/After Probability Comparison",
        "",
        f"Before: `{Path(before_path).resolve().relative_to(ROOT)}` · After: `{Path(after_path).resolve().relative_to(ROOT)}`",
        "Generated by `scripts/compare_golden_references.py` from the golden fixture set (isolated, deterministic).",
        "",
        "## Summary",
        "",
        "| Cause | Description | Changed values |",
        "|---|---|---|",
        f"| E1 | synthetic XGBoost blend weight → 0 (`estimate_probabilities`) | {len(attributed['E1'])} |",
        f"| E2 | unknown (hash-fallback) teams report 0 matches → data quality and everything downstream | {len(attributed['E2'])} |",
        f"| E3 | synthetic XGBoost removed from BILQE consensus (`qualification` block) | {len(attributed['E3'])} |",
        f"| **UNINTENDED** | not explained by E1–E3 | **{len(unintended)}** |",
        "",
        "Fixtures containing a hash-fallback team (E2 scope; each path maps league names its own way):",
        f"- `estimate_probabilities`: {', '.join(sorted(blind['estimate_probabilities'])) or 'none'}",
        f"- `match_analysis`: {', '.join(sorted(blind['match_analysis'])) or 'none'}",
        "",
        "## 1. `estimate_probabilities` (feeds `run_pipeline` pick selection) — every fixture",
        "",
        "| Fixture | Group | Source | Data quality | Home | Draw | Away | Over 2.5 | BTTS yes |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for h, a, lg, _ in FIXTURES:
        key = f"{h} v {a} [{lg}]"
        b, n = before["estimate_probabilities"][key], after["estimate_probabilities"][key]
        group = "unknown team" if key in blind["estimate_probabilities"] else ("low data quality" if n["data_quality"] < 45 else "known teams")

        def pair(getter):
            x, y = getter(b), getter(n)
            return f"{_fmt(x)} → {_fmt(y)}" if x != y else _fmt(x)

        lines.append(
            f"| {key} | {group} | {pair(lambda d: d['source'])} | {pair(lambda d: d['data_quality'])} | "
            f"{pair(lambda d: d['1X2']['home'])} | {pair(lambda d: d['1X2']['draw'])} | {pair(lambda d: d['1X2']['away'])} | "
            f"{pair(lambda d: d['O/U 2.5']['over'])} | {pair(lambda d: d['BTTS']['yes'])} |"
        )

    lines += [
        "",
        "## 2. `match_analysis` (user-facing analysis, runtime gate, BILQE) — per fixture",
        "",
        "| Fixture | Data quality | Quality class | Confident picks | BILQE tiers (S/A/B/C) | Market probabilities changed | Max abs change (pp) |",
        "|---|---|---|---|---|---|---|",
    ]
    for key in after["match_analysis"]:
        b, n = before["match_analysis"][key], after["match_analysis"][key]
        fb = {m["market"]: m["probability"] for sec in b["full_analysis"].values() for m in sec}
        fa = {m["market"]: m["probability"] for sec in n["full_analysis"].values() for m in sec}
        changed = {m: (fb.get(m), fa.get(m)) for m in fb.keys() | fa.keys() if fb.get(m) != fa.get(m)}
        max_delta = max((abs((y or 0) - (x or 0)) for x, y in changed.values()), default=0.0)

        def tiers(d):
            tc = d["qualification"]["tier_counts"]
            return "/".join(str(tc.get(t, 0)) for t in ("S", "A", "B", "C"))

        def pair(x, y):
            return f"{_fmt(x)} → {_fmt(y)}" if x != y else _fmt(x)

        lines.append(
            f"| {key} | {pair(b['data_quality_score'], n['data_quality_score'])} | "
            f"{pair(b['prediction_quality'], n['prediction_quality'])} | "
            f"{pair(b['total_confident_picks'], n['total_confident_picks'])} | {pair(tiers(b), tiers(n))} | "
            f"{len(changed)} of {len(fa)} | {_fmt(round(max_delta, 1))} |"
        )

    lines += ["", "## 3. Affected betting markets (unknown-team fixtures, every changed market)", ""]
    for key in after["match_analysis"]:
        if key not in blind["match_analysis"]:
            continue
        b, n = before["match_analysis"][key], after["match_analysis"][key]
        lines += [f"### {key}", "", "| Section | Market | Before | After | Δ pp |", "|---|---|---|---|---|"]
        for section in n["full_analysis"]:
            fb = {m["market"]: m["probability"] for m in b["full_analysis"].get(section, [])}
            for m in n["full_analysis"][section]:
                old = fb.get(m["market"])
                if old != m["probability"]:
                    lines.append(f"| {section} | {m['market']} | {_fmt(old)} | {_fmt(m['probability'])} | {_fmt(round(m['probability'] - (old or 0), 1))} |")
        lines.append("")

    lines += ["## 4. Unintended differences", ""]
    lines += [f"- `{u}`" for u in unintended] or ["None. Every changed value is explained by E1, E2 or E3."]
    lines += ["", "## 5. All attributed differences (raw)", ""]
    for cause in ("E1", "E2", "E3"):
        lines += [f"<details><summary>{cause}: {len(attributed[cause])} values</summary>", "", "```"]
        lines += attributed[cause] or ["(none)"]
        lines += ["```", "</details>", ""]

    Path(out_path).write_text("\n".join(lines) + "\n")
    print(f"E1={len(attributed['E1'])} E2={len(attributed['E2'])} E3={len(attributed['E3'])} UNINTENDED={len(unintended)}")
    return 1 if unintended else 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:4]))
